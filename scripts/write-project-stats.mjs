/**
 * Writes src/data/testCount.ts, and with --check verifies the committed copy
 * still matches the suite that just ran.
 *
 *   npm run stats          regenerate it
 *   npm run stats:check    fail if it has drifted (runs after `npm test`)
 *
 * Only the test count lives in a file. Everything else the founder panel prints
 * is counted by vite.config.ts at build time, because those numbers move on
 * every edit to any source file and a check that goes red on unrelated work
 * gets deleted rather than obeyed.
 *
 * The check is wired to `posttest` rather than to a test, because a test cannot
 * ask the runner how many tests there are while it is one of them. Running
 * after the suite means the report describes the run that just happened -- the
 * signal comes from the far end, not from a second guess at it.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { readTestCount, REPORT } from './projectStats.mjs'

const root = process.cwd()
const OUT = join(root, 'src', 'data', 'testCount.ts')
const check = process.argv.includes('--check')

const tests = readTestCount(root)
if (tests === null) {
  console.error(
    `No usable test report at ${REPORT}.\n` +
      'Run `npm test` first, over the whole suite -- the test count comes from the\n' +
      'runner, because a regex over the source cannot expand `it.each` into the\n' +
      'tests it becomes, and a report from a single file is not the suite.',
  )
  process.exit(1)
}

const text = `// Generated by scripts/write-project-stats.mjs -- do not edit by hand.
// Run \`npm run stats\` after adding or removing tests.
//
// This is the one figure on the founder panel that cannot be counted from the
// source: one \`it.each\` over five files is one match and five tests, so only
// the runner knows. \`npm test\` checks this file on the way out.

/** Tests vitest ran, as vitest counted them. */
export const testCount = ${tests}
`

if (check) {
  const before = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (before !== text) {
    console.error(
      `src/data/testCount.ts says ${before.match(/testCount = (\d+)/)?.[1] ?? 'nothing'} ` +
        `and the runner just ran ${tests}.\n` +
        'The founder panel would print a number the suite no longer matches.\n' +
        'Run `npm run stats` and commit it.',
    )
    process.exit(1)
  }
  console.log(`test count is current (${tests})`)
} else {
  writeFileSync(OUT, text)
  console.log(`wrote src/data/testCount.ts (${tests})`)
}
